"""Run the actual ROM, switch overlays, save settings, then exit cleanly."""
from pathlib import Path
import rp6502


with rp6502.Emu() as emu:
    def message():
        return bytes.fromhex(emu.cmd('dump _note 100')).split(b'\0',1)[0].decode('ascii')
    emu.cmd('run 1200')  # Includes the unskippable five-second cover.
    assert 'EXIT' not in emu.status(), 'ROM exited before the sky view'
    emu.cmd('peek _ovl_failed 0')
    emu.cmd('wait _state 2 7200')  # Local rise/set calculation has completed.
    emu.cmd('run 60')
    emu.cmd('shot "sky.png"')
    # Console sequences carry generic Ctrl; physical USB bits select LCtrl.
    emu.cmd('peek _fov 120')
    emu.cmd('press lctrl')
    emu.cmd('peek xram:0xffdc 1')
    emu.cmd('key left+ctrl')
    emu.cmd('run 120')
    emu.cmd('peek _fov 110')
    emu.cmd('release lctrl')
    emu.cmd('press rctrl')
    emu.cmd('key left+ctrl')
    emu.cmd('run 120')
    emu.cmd('peek _fov 110')
    emu.cmd('press lctrl')
    emu.cmd('key right+ctrl')
    emu.cmd('run 120')
    emu.cmd('peek _fov 110')
    emu.cmd('release rctrl')
    emu.cmd('key right+ctrl')
    emu.cmd('run 120')
    emu.cmd('peek _fov 120')
    emu.cmd('release lctrl')
    emu.cmd('key left+ctrl')
    emu.cmd('run 120')
    emu.cmd('peek _fov 120')
    emu.cmd('peek _bearing 180')
    emu.cmd('key right+shift')
    emu.cmd('run 120')
    emu.cmd('peek _bearing 225')
    emu.cmd('peek _fov 120')
    emu.cmd('key left+shift')
    emu.cmd('run 120')
    emu.cmd('peek _bearing 180')
    for key in ('h', 'h+shift', 'q', 'q+shift', 'x', 'x+shift', 'f', 'f+shift', 'escape'):
        emu.cmd('key '+key)
        emu.cmd('run 60')
        emu.cmd('peek _bearing 180')
        assert 'EXIT' not in emu.status()
    emu.cmd('key s')
    emu.cmd('run 180')
    emu.cmd('peek _solar_visible 1')
    emu.cmd('peek _ovl_failed 0')
    emu.cmd('shot "solar.png"')
    for key in ('x', 's', 's+ctrl', 'r+ctrl', 'q', 'q+shift'):
        emu.cmd('key '+key)
        emu.cmd('run 30')
        emu.cmd('peek _solar_visible 1')
        assert 'EXIT' not in emu.status()
    emu.cmd('key escape')
    emu.cmd('run 180')
    emu.cmd('peek _solar_visible 0')
    emu.cmd('key l')
    emu.cmd('run 120')
    emu.cmd('peek _editing 1')
    emu.cmd('key escape')
    emu.cmd('run 120')
    emu.cmd('peek _editing 0')
    emu.cmd('key k')
    emu.cmd('run 180')
    emu.cmd('peek _cities_active 1')
    emu.cmd('peek _ovl_failed 0')
    emu.cmd('shot "cities.png"')
    emu.cmd('key escape')
    emu.cmd('run 120')
    emu.cmd('peek _cities_active 0')
    emu.cmd('key s+ctrl')
    emu.cmd('run 120')
    assert message() == '[INFO] Configuration saved'
    emu.cmd('run 300')
    assert message() == '', 'Save result must disappear after five seconds without input'
    for control in ('lctrl','rctrl'):
        emu.cmd('key right')
        emu.cmd('key g')
        emu.cmd('key equal+shift')
        emu.cmd('run 120')
        emu.cmd('press '+control)
        emu.cmd('key r+ctrl')
        emu.cmd('run 120')
        assert message() == '[INFO] Configuration reloaded'
        emu.cmd('release '+control)
        emu.cmd('wait _calculating 0 14400')
        emu.cmd('peek _bearing 180')
        emu.cmd('peek _grid 0')
        emu.cmd('peek _live 0')
        emu.cmd('peek _playing 0')
        emu.cmd('peek (_moment+4) 20 0 0')
    emu.cmd('shot "reloaded.png"')
    emu.cmd('run 300')
    assert message() == '', 'Reload result must disappear after five seconds without input'
    # Full-detail simulation: a five-minute step, then manual +15 pauses it.
    emu.cmd('type "gggccctp"')
    emu.cmd('wait _planets 1 7200')
    emu.cmd('peek _grid 3')
    emu.cmd('peek _constellation_mode 3')
    emu.cmd('peek _trails 1')
    emu.cmd('peek _planets 1')
    emu.cmd('wait _calculating 0 14400')
    emu.cmd('key space')
    emu.cmd('wait (_moment+5) 5 7200')
    emu.cmd('peek _playing 1')
    emu.cmd('key space')
    emu.cmd('wait _playing 0 120')
    emu.cmd('peek _live 0')
    paused = emu.cmd('dump _moment 7')
    emu.cmd('run 120')
    assert emu.cmd('dump _moment 7') == paused, 'Space must pause without returning to LIVE'
    emu.cmd('key space')
    emu.cmd('wait _playing 1 120')
    emu.cmd('peek _live 0')
    emu.cmd('key equal+shift')
    emu.cmd('wait _playing 0 120')
    emu.cmd('run 60')
    emu.cmd('wait _calculating 0 14400')
    emu.cmd('peek (_moment+4) 20 20 0')
    emu.cmd('shot "simulation.png"')
    emu.cmd('key q+ctrl')
    emu.cmd('wait exit 120')
    emu.cmd('expect exit 0')
assert (Path('save')/'sidera.cfg').is_file(), 'Ctrl+S must save the configuration'
assert 'Time 2026-11-12 20:00:00' in (Path('save')/'sidera.cfg').read_text(), 'Monitor argv must preserve /date'
print('PASS: ROM startup, physical LCtrl-only FOV, Shift directions, retired H, overlays, SAVE and exit')
