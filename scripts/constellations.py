"""Build the fixed-point catalogue offline from data/constellations.json.

To refresh source data, pass --import-dir containing d3-celestial's
constellations.lines.json, constellations.json and stars.8.json.
See data/NOTICE.txt for provenance and redistribution terms.
"""
import argparse
import json
import math
from pathlib import Path

root = (Path(__file__).resolve().parents[1] / 'src')
p = argparse.ArgumentParser()
p.add_argument('--import-dir', type=Path)
p.add_argument('--output', type=Path, default=root.parent/'build/generated/tables/constellations.h')
a = p.parse_args()
a.output.parent.mkdir(parents=True, exist_ok=True)
target = root / 'data/constellations.json'
if a.import_dir:
    target=a.output.parent.parent/'data/constellations.json'
    def source(name):
        return json.loads((a.import_dir / name).read_text(encoding='utf8'))['features']
    source_stars = source('stars.8.json')
    stars = {tuple(s['geometry']['coordinates']): s for s in source_stars}
    names = {s['id']: s['properties']['name'] for s in source('constellations.json')}
    # IAU names: Serpens is one constellation with two disconnected parts.
    names.update(Ser='Serpens', CrA='Corona Australis', Boo='Boötes')
    points, indices, groups = [], {}, {}
    for c in source('constellations.lines.json'):
        group = groups.setdefault(c['id'], {'name': names[c['id']], 'abbr': c['id'], 'edges': []})
        for line in c['geometry']['coordinates']:
            ids = []
            for point in line:
                key = tuple(point)
                if key not in indices:
                    s = stars[key]
                    indices[key] = len(points)
                    points.append([s['id'], *point, s['properties']['mag']])
                ids.append(indices[key])
            group['edges'].extend(zip(ids, ids[1:]))
    # Additional navigation stars are points, not new figure segments.
    by_hip = {s['id']: s for s in source_stars}
    for abbr, hip in [('Cru', 60260), ('Oct', 104382)]:
        s = by_hip[hip]
        key = tuple(s['geometry']['coordinates'])
        if key not in indices:
            indices[key] = len(points)
            points.append([hip, *key, s['properties']['mag']])
        groups[abbr]['points'] = [indices[key]]
    data = {'epoch': 'J2000.0', 'stars': points,
            'constellations': [groups[k] for k in sorted(groups)]}
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf8')

data = json.loads(target.read_text(encoding='utf8'))
groups, stars = data['constellations'], data['stars']
assert len(groups) == len({g['abbr'] for g in groups}) == 88
assert all(len(g['abbr']) == 3 and g['edges'] for g in groups)
def records(group):
    # A repeated index represents an isolated star in the existing renderer:
    # selection/label bounds include it, but no connecting line is introduced.
    return group['edges'] + [[i, i] for i in group.get('points', [])]

record_count = sum(len(records(g)) for g in groups)
assert len(stars) <= 760 and 0xF400 + record_count * 4 <= 0x10000
a.output.with_name('catalogue.h').write_text(
    '/* Generated by tools/constellations.py. */\n'
    '#ifndef SIDERA_CATALOGUE_H\n#define SIDERA_CATALOGUE_H\n'
    f'#define SIDERA_STAR_COUNT {len(stars)}u\n'
    f'#define SIDERA_RECORD_COUNT {record_count}u\n#endif\n', encoding='ascii')
out = ['/* Generated by tools/constellations.py; see data/NOTICE.txt. */',
       f'#define STAR_COUNT {len(stars)}u', '#define CONSTELLATION_COUNT 88u',
       *[f'#define CS_{g["abbr"].upper()} {i}u' for i,g in enumerate(groups)],
       '#ifndef SIDERA_EXTERNAL_STARS', 'static const Star stars[STAR_COUNT] = {']
sizes=[]
for hip, ra, dec, mag in stars:
    r, d = math.radians(ra), math.radians(dec)
    v = [round(16384*x) for x in (math.cos(d)*math.cos(r), math.cos(d)*math.sin(r), math.sin(d))]
    size = 3 if mag < 1.5 else 2 if mag < 3.5 else 1
    sizes.append(size)
    out.append('{{'+','.join(map(str,v))+'},'+str(size)+'},')
out += ['};','#else','#ifndef SIDERA_EXTERNAL_METADATA','static const unsigned char star_sizes[STAR_COUNT] = {',
        ','.join(map(str,sizes)), '};','#endif','#endif','#ifndef SIDERA_EXTERNAL_STARS','static const Edge edges[] = {']
for g in groups:
    for i,j in records(g):
        assert 0 <= i < len(stars) and 0 <= j < len(stars)
        assert i != j or i in g.get('points', [])
        out.append('{%d,%d},' % (i,j))
out += ['};','#endif','#ifndef SIDERA_EXTERNAL_METADATA', 'static const Constellation figures[CONSTELLATION_COUNT] = {']
offset = 0
for g in groups:
    label = (g['name']+' ['+g['abbr']+']').replace('ö', '\\004')
    assert len(g['name']+' ['+g['abbr']+']')*6+2 <= 600
    out.append('{%d,%d,"%s"},' % (offset, len(records(g)), label))
    offset += len(records(g))
out += ['};','#endif', '']
a.output.write_text('\n'.join(out), encoding='ascii')
print(f'{len(groups)} constellations, {len(stars)} stars, {offset} segment/point records')
